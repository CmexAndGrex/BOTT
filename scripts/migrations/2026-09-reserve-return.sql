-- Сценарий «Возврат из запаса» для формы /apply.
--
-- Заявка на вступление раньше описывала только новобранца. Возвращающийся из
-- запаса подаёт ту же форму, но решение по ней другое: бойца не зачисляют
-- заново, а восстанавливают (active = true), переносят его строку с листа
-- «Запас» в свободную строку «Вакант» подразделения и возвращают роли Discord,
-- сохранённые в колонке V листа «Запас». Чтобы модерация видела разницу до
-- принятия решения, вид заявки хранится явной колонкой, а не выводится из
-- текста: строка свободного комментария не должна управлять правами.

-- Вид заявки: recruit — новобранец (поведение по умолчанию), reserve_return —
-- возврат из запаса. Значение по умолчанию сохраняет прежние заявки как есть.
ALTER TABLE "recruit_applications"
  ADD COLUMN IF NOT EXISTS "kind" varchar(20) NOT NULL DEFAULT 'recruit';

-- ФИО возвращающегося: в табеле и листе «Запас» боец записан ФИО, а позывной
-- он мог за время службы сменить. Отдельная колонка, а не общее поле about:
-- по этому значению ищется строка на листе «Запас».
ALTER TABLE "recruit_applications"
  ADD COLUMN IF NOT EXISTS "full_name" text;

-- Очередь модерации фильтрует заявки по виду («Запрос на возврат из запаса»)
CREATE INDEX IF NOT EXISTS "recruit_applications_kind_status_idx"
  ON "recruit_applications" ("kind", "status");