-- ============================================================================
-- Подразделение, выбранное кандидатом в форме заявки (/apply)
-- ============================================================================
-- Зачем: форма /apply теперь спрашивает подразделение явно (обязательный
-- выбор: «Танковая рота» или «Артиллерийский дивизион»). Значение нужно, чтобы
-- при одобрении заявки:
--   * записать бойца в ПРАВИЛЬНЫЙ лист ШДС (shds_sheet_tank / shds_sheet_art);
--   * выдать роль Discord выбранного подразделения;
--   * сохранить unit в division_members без ручного выбора модератора.
--
-- Применение (вручную, сначала на копии базы):
--   psql "$DATABASE_URL" -f scripts/migrations/2026-10-recruit-application-unit.sql
--
-- Миграция идемпотентна: повторный запуск ничего не ломает.
-- ============================================================================

ALTER TABLE "recruit_applications" ADD COLUMN IF NOT EXISTS "unit" text;

-- Допустимые значения — UNITS из src/lib/recruits.ts. CHECK не ставится
-- намеренно: список подразделений может расшириться, а старые строки с NULL
-- (заявки Google-формы и заявки до этой миграции) должны оставаться валидными.

COMMENT ON COLUMN "recruit_applications"."unit" IS
  'Подразделение из формы /apply: «Танковая рота» или «Артиллерийский дивизион»';
