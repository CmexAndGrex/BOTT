-- ============================================================================
-- Исправление флагов active после регрессии с тумблером отпуска
-- ============================================================================
-- Причина: в табеле «Состав» появился слепой тумблер (Switch), который вместо
-- штатного управления отпуском сбрасывал бойцам флаг active. Из-за этого в
-- «Контроле» (/api/control) выборка по active = true возвращала пустой состав,
-- и страница показывала «Нет активных бойцов».
--
-- Правило исправления: действующие бойцы (status != 'dismissed') снова
-- считаются в строю (active = true). Выбывшие в запас (status = 'dismissed')
-- НЕ трогаем — их inactive состояние корректно и означает «в запасе».
--
-- Применение (вручную, на копии базы сначала!):
--   psql "$DATABASE_URL" -f scripts/migrations/2026-09-fix-active-flags.sql
--
-- Скрипт идемпотентен: повторный запуск безопасен, обновляются только те
-- строки, у которых флаг неверен.
-- ============================================================================

UPDATE "division_members"
   SET "active" = true,
       "updated_at" = now()
 WHERE "active" = false
   AND "status" <> 'dismissed';
